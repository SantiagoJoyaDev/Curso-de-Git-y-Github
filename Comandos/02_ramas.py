# ---------- RAMAS ----------

# Para crear un rama --> git branch "Nombre de la rama"
# Para la eliminacion de ramas --> git branch -d "Nombre de la rama"
# Para renombrar una rama --> git branch -m "Nombre de la rama"
# Para traerme los cambios de una rama diferente entonces sirve para mezclar y actualizar todas las ramas a la main --> git merge "Nombre de la rama"
